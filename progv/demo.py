"""`python -m progv.demo`: run the teacher pipeline and the toy student on the synthetic cases."""
from __future__ import annotations

import argparse

from .claims import Case, Element, load_all_cases
from .llm import make_client
from .pipeline import Report, analyze
from .student import Student, agreement, train_student
from .synth import generate_cases


def describe(el: Element) -> str:
    if el.chars is not None and el.source == "title":
        where = f"title chars {el.chars[0]}-{el.chars[1]}"
    elif el.span is not None:
        where = f"{el.span[0]:g}s-{el.span[1]:g}s"
    else:
        where = "-"
    return f'{el.id} = "{el.value}" [{where}]'


def show_chain(case: Case, rep: Report) -> None:
    docs = {d.id: d for d in case.evidence}
    seen = set()
    for src, rel, dst in rep.chain:
        for n in (src, dst):
            if n in docs and n not in seen:
                seen.add(n)
                d = docs[n]
                print(f"    {n}: {d.type} | {d.source} | {d.facts or d.text}")
        print(f"    {src} --{rel}--> {dst}")


def show_case(case: Case, rep: Report, student: Student, show_program: bool) -> None:
    print(f"\n=== {case.id} (SYNTHETIC toy post) ===")
    print(f'title: "{case.title}"')
    print("claim elements U:")
    for el in rep.elements:
        print("  " + describe(el))
    n_stmt = sum(1 for ln in rep.program_text.splitlines() if ln and not ln.startswith("#"))
    if show_program:
        print("verification program (typed DSL, generated by MockLLM):")
        print("".join("  " + ln + "\n" for ln in rep.program_text.splitlines()), end="")
    else:
        print(f"verification program: {n_stmt} statements (use --show-program to print)")
    if rep.fallback:
        print("type check FAILED -> fallback, no verdict:", *rep.errors, sep="\n  ")
        return
    print(f"type check: OK ({n_stmt} statements); evidence retrieved: "
          f"{sum(len(v) for v in rep.trace.base.env.values())} docs")
    print("sub-claims:")
    for sc in rep.trace.base.subclaims:
        print(f"  {sc.op:6s} {sc.element:15s} {sc.judgement.status:12s} {sc.judgement.detail}")
    print(f"P(false) = {rep.p_false:.3f}  ->  verdict: {rep.verdict.upper()}  (type: {rep.label})")
    print("localized false element(s):", "; ".join(describe(e) for e in rep.localized) or "none")
    if rep.chain:
        print("provenance chain (claim element -> evidence -> footage):")
        show_chain(case, rep)
    pred = student.predict(case)
    print("responsibility R(u) by single-element counterfactual intervention (student R^ = toy distilled):")
    print(f"  {'element':15s} {'action':8s} {'changed':8s} {'R(u)':>6s} {'R^(u)':>6s}")
    for el in rep.elements:
        sc, dl = rep.responsibility[el.id], rep.trace.deltas[el.id]
        mark = "  <-- false" if el.id in rep.grounded_ids else ""
        print(f"  {el.id:15s} {dl.action:8s} {str(dl.changed):8s} {sc.value:6.3f} {pred.label_scores[el.id]:6.3f}{mark}")
    if len(rep.localized) > 1:
        print("  note: with several false elements, repairing one leaves the verdict false, so each R(u) is small.")
    print(f"distilled student (no LLM, no program): verdict {pred.verdict.upper()}, "
          f"localized {', '.join(pred.localized) or 'none'}")


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="ProgV-Trace toy demo (synthetic data, offline)")
    ap.add_argument("--case", help="run only the case with this id")
    ap.add_argument("--llm", default="mock", choices=["mock", "openai", "anthropic"],
                    help="program generator; mock is deterministic and offline (default)")
    ap.add_argument("--show-program", action="store_true", help="print the program of every case")
    ap.add_argument("--train-cases", type=int, default=60, help="synthetic cases used to train the toy student")
    args = ap.parse_args(argv)

    print("ProgV-Trace demo: all inputs are SYNTHETIC; this is not the paper's pipeline and reports no paper result.")
    llm = make_client(args.llm)
    student = train_student(args.train_cases, seed=0)
    cases = [c for c in load_all_cases() if args.case in (None, c.id)]
    if not cases:
        raise SystemExit(f"no case with id {args.case!r}")
    for i, case in enumerate(cases):
        show_case(case, analyze(case, llm), student, args.show_program or i == 0)
    held = agreement(student, generate_cases(100, seed=1))
    print("\n--- toy student vs. teacher on held-out generated synthetic cases "
          f"(n={int(held['n'])}, computed here, not a benchmark) ---")
    print(f"verdict agreement {held['verdict']:.2f}, localization agreement {held['localization']:.2f}")


if __name__ == "__main__":
    main()
